

from tradingagents.agents.utils.agent_utils import build_instrument_context


def create_bull_researcher(llm):
    def bull_node(state) -> dict:
        investment_debate_state = state["investment_debate_state"]
        history = investment_debate_state.get("history", "")
        bull_history = investment_debate_state.get("bull_history", "")

        current_response = investment_debate_state.get("current_response", "")
        market_research_report = state["market_report"]
        sentiment_report = state["sentiment_report"]
        news_report = state["news_report"]
        fundamentals_report = state["fundamentals_report"]
        instrument_context = build_instrument_context(state["company_of_interest"])

        prompt = f"""You are a Bull Analyst advocating for bullish exposure to the instrument. Your task is to build a strong, evidence-based case emphasizing upside potential, relative advantages, and positive market indicators. Leverage the provided research and data to address concerns and counter bearish arguments effectively.

Instrument context: {instrument_context}

Key points to focus on:
- Growth Potential: Highlight the instrument's upside drivers, improving fundamentals, and supportive macro or market regime.
- Competitive/Relative Advantages: Emphasize factors like stronger relative growth, policy support, market positioning, or dominant business positioning where relevant.
- Positive Indicators: Use technicals, sentiment, macro data, financial health, industry trends, and recent positive news as evidence.
- Bear Counterpoints: Critically analyze the bear argument with specific data and sound reasoning, addressing concerns thoroughly and showing why the bull perspective holds stronger merit.
- Engagement: Present your argument in a conversational style, engaging directly with the bear analyst's points and debating effectively rather than just listing data.

Resources available:
Market research report: {market_research_report}
Social media sentiment report: {sentiment_report}
Latest world affairs news: {news_report}
Company fundamentals report: {fundamentals_report}
Conversation history of the debate: {history}
Last bear argument: {current_response}
Use this information to deliver a compelling bull argument, refute the bear's concerns, and engage in a dynamic debate that demonstrates the strengths of the bull position.
"""

        response = llm.invoke(prompt)

        argument = f"Bull Analyst: {response.content}"

        new_investment_debate_state = {
            "history": history + "\n" + argument,
            "bull_history": bull_history + "\n" + argument,
            "bear_history": investment_debate_state.get("bear_history", ""),
            "current_response": argument,
            "count": investment_debate_state["count"] + 1,
        }

        return {"investment_debate_state": new_investment_debate_state}

    return bull_node
